import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { afterEach, beforeEach, describe, expect, test } from "vitest";
import { applyBuild, planBuild } from "../../../src/core/build/index.js";
import type { BuildPlan, BuildReport } from "../../../src/core/build/index.js";
import { loadConfig } from "../../../src/core/config/load.js";
import { resolveSelection } from "../../../src/core/env/index.js";
import { loadFactory } from "../../../src/core/factory/index.js";
import { isolateGitConfig } from "../hooks/helpers.js";
import { makeRepo } from "../../helpers/makeRepo.js";
import type { TempRepo } from "../../helpers/makeRepo.js";

const require = createRequire(import.meta.url);
const PACKAGE_VERSION = (require("../../../package.json") as { version: string }).version;

const GENERATED = (source: string): string =>
  `<!-- Generated by metafab build from ${source}/. Edit the source, then run metafab build. -->`;

const repos: TempRepo[] = [];

function track(repo: TempRepo): TempRepo {
  repos.push(repo);
  return repo;
}

afterEach(async () => {
  await Promise.all(repos.splice(0).map((repo) => repo.cleanup()));
});

/** Builds with the selection `--env` would give; without one, every value. */
async function build(
  root: string,
  env?: readonly string[],
): Promise<{ plan: BuildPlan; report: BuildReport }> {
  const factory = await loadFactory(root);
  const config = await loadConfig(factory.dir);
  const selection = await resolveSelection(factory.factoryYaml?.env ?? [], {
    root,
    options: env,
    processEnv: {},
  });
  const plan = await planBuild(factory, config, PACKAGE_VERSION, { selection });
  const report = await applyBuild(plan);
  return { plan, report };
}

const FACTORY_YAML = [
  "format: 2",
  "name: demo",
  "env:",
  "  harness: { values: [amp, claude] }",
  "",
].join("\n");

const METAFAB_YAML = "agents: [codex]\nmetafab-skill: false\n";

/** A partial whose switch gives each harness its own procedure. */
const SUB_AGENTS = [
  "---",
  "title: Sub-agents",
  "---",
  "<!-- factory:switch env.harness -->",
  "<!-- factory:case amp -->",
  "Start an Amp thread with the plan.",
  "<!-- factory:case claude -->",
  "Start a Claude Code session with the plan.",
  "<!-- factory:endswitch -->",
  "",
].join("\n");

const BUILD_PLAN = [
  "---",
  "name: build-plan",
  "description: Build a plan. Use when a plan is ready.",
  "---",
  "",
  "# Build plan",
  "",
  "<!-- factory:import ../../partials/sub-agents.md -->",
  "",
  "After the partial.",
  "",
].join("\n");

function skill(name: string, description: string, body: string): string {
  return `---\nname: ${name}\ndescription: ${description}\n---\n${body}`;
}

describe("build with imports", () => {
  let isolation: Awaited<ReturnType<typeof isolateGitConfig>>;

  beforeEach(async () => {
    isolation = await isolateGitConfig();
  });

  afterEach(() => {
    isolation.restore();
  });

  test("installs only the selected harness's text from an imported partial", async () => {
    const repo = track(
      await makeRepo({
        ".factory/factory.yaml": FACTORY_YAML,
        ".factory/metafab.yaml": METAFAB_YAML,
        ".factory/partials/sub-agents.md": SUB_AGENTS,
        ".factory/workflows/build-plan/SKILL.md": BUILD_PLAN,
      }),
    );

    const { plan } = await build(repo.root, ["harness=amp"]);

    expect(plan.errors).toEqual([]);
    expect(plan.conflicts).toEqual([]);

    const installed = await readFile(repo.path(".agents/skills/build-plan/SKILL.md"), "utf8");
    expect(installed).toBe(
      [
        "---",
        "name: build-plan",
        "description: Build a plan. Use when a plan is ready.",
        "---",
        GENERATED(".factory/workflows/build-plan"),
        "",
        "# Build plan",
        "",
        "Start an Amp thread with the plan.",
        "",
        "After the partial.",
        "",
      ].join("\n"),
    );
    // The partial's frontmatter never reaches the importing file.
    expect(installed).not.toContain("title: Sub-agents");
    expect(installed).not.toContain("Claude Code session");
  });

  test("labels each case when two values are selected", async () => {
    const repo = track(
      await makeRepo({
        ".factory/factory.yaml": FACTORY_YAML,
        ".factory/metafab.yaml": METAFAB_YAML,
        ".factory/partials/sub-agents.md": SUB_AGENTS,
        ".factory/workflows/build-plan/SKILL.md": BUILD_PLAN,
      }),
    );

    const { plan } = await build(repo.root, ["harness=amp,claude"]);

    expect(plan.errors).toEqual([]);
    expect(await readFile(repo.path(".agents/skills/build-plan/SKILL.md"), "utf8")).toBe(
      [
        "---",
        "name: build-plan",
        "description: Build a plan. Use when a plan is ready.",
        "---",
        GENERATED(".factory/workflows/build-plan"),
        "",
        "# Build plan",
        "",
        "**When harness is amp:**",
        "Start an Amp thread with the plan.",
        "**When harness is claude:**",
        "Start a Claude Code session with the plan.",
        "",
        "After the partial.",
        "",
      ].join("\n"),
    );
  });

  test("installs a partial in a skill directory and inserts it into another skill", async () => {
    const repo = track(
      await makeRepo({
        ".factory/factory.yaml": FACTORY_YAML,
        ".factory/metafab.yaml": METAFAB_YAML,
        ".factory/skills/alpha/SKILL.md": skill(
          "alpha",
          "Alpha. Use when testing.",
          "\n# Alpha\n",
        ),
        ".factory/skills/alpha/steps.md": SUB_AGENTS,
        ".factory/skills/beta/SKILL.md": skill(
          "beta",
          "Beta. Use when testing.",
          "\n# Beta\n\n<!-- factory:import ../alpha/steps.md -->\n\nEnd.\n",
        ),
      }),
    );

    const { plan } = await build(repo.root, ["harness=claude"]);

    expect(plan.errors).toEqual([]);

    // Its own file is installed, rendered for the selection, with its
    // frontmatter kept because the file is not a SKILL.md.
    expect(await readFile(repo.path(".agents/skills/alpha/steps.md"), "utf8")).toBe(
      [
        "---",
        "title: Sub-agents",
        "---",
        "Start a Claude Code session with the plan.",
        "",
      ].join("\n"),
    );

    // Another skill imports it: only the body arrives, without the frontmatter.
    expect(await readFile(repo.path(".agents/skills/beta/SKILL.md"), "utf8")).toBe(
      [
        "---",
        "name: beta",
        "description: Beta. Use when testing.",
        "---",
        GENERATED(".factory/skills/beta"),
        "",
        "# Beta",
        "",
        "Start a Claude Code session with the plan.",
        "",
        "End.",
        "",
      ].join("\n"),
    );
  });

  test("a second run rereads an edited partial", async () => {
    const repo = track(
      await makeRepo({
        ".factory/factory.yaml": FACTORY_YAML,
        ".factory/metafab.yaml": METAFAB_YAML,
        ".factory/partials/sub-agents.md": SUB_AGENTS,
        ".factory/workflows/build-plan/SKILL.md": BUILD_PLAN,
      }),
    );

    const first = await build(repo.root, ["harness=amp"]);
    expect(first.plan.errors).toEqual([]);
    expect(await readFile(repo.path(".agents/skills/build-plan/SKILL.md"), "utf8")).toContain(
      "Start an Amp thread with the plan.",
    );

    await writeFile(
      repo.path(".factory/partials/sub-agents.md"),
      SUB_AGENTS.replace("Start an Amp thread with the plan.", "Start an Amp thread with the review."),
    );

    const second = await build(repo.root, ["harness=amp"]);
    expect(second.plan.errors).toEqual([]);
    expect(second.report.changed).toContainEqual({
      path: ".agents/skills/build-plan/SKILL.md",
      action: "updated",
    });

    const installed = await readFile(repo.path(".agents/skills/build-plan/SKILL.md"), "utf8");
    expect(installed).toContain("Start an Amp thread with the review.");
    expect(installed).not.toContain("Start an Amp thread with the plan.");
  });
});
