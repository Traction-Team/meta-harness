describe("compileSkill", () => {
  test("copies every file and inserts the comment after the frontmatter", async () => {
    const result = await compileSkill(source, { factoryDir: fixture });

    expect(result.problems).toEqual([]);
    expect(result.name).toBe("demo-skill");
    expect(result.files.map((file) => file.path)).toEqual([
      "SKILL.md",
      "data.bin",
      "nested/helper.md",
      "notes.txt",
      "run.sh",
    ]);

    const files = new Map(result.files.map((file) => [file.path, file]));
    const skill = files.get("SKILL.md")!.content.toString("utf8");

    expect(skill.startsWith("---\nname: demo-skill\ndescription:")).toBe(true);
    expect(skill).toContain(
      "---\n<!-- Generated by metafab build from .factory/skills/demo-skill/. Edit the source, then run metafab build. -->\n\n# Demo skill",
    );
    expect(skill).not.toContain("\r");
  });

  test("writes CRLF text as LF and leaves binary bytes unchanged", async () => {
    const result = await compileSkill(source, { factoryDir: fixture });
    const files = new Map(result.files.map((file) => [file.path, file]));

    expect(files.get("notes.txt")!.content.toString("utf8")).toBe("first line\nsecond line\n");
    expect(files.get("data.bin")!.content).toEqual(
      Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x00, 0x00, 0x01, 0x02, 0xff]),
    );
  });

  test("copies a file that is not valid UTF-8 byte for byte", async () => {
    const invalid = Buffer.from([0xc3, 0x28, 0xa0, 0xa1]);
    const repo = await makeRepo({
      ".factory/skills/demo/SKILL.md":
        "---\nname: demo\ndescription: A demo skill. Use when testing.\n---\n\n# Demo\n",
      ".factory/skills/demo/data.bin": invalid,
    });

    try {
      const result = await compileSkill(
        {
          dir: repo.path(".factory/skills/demo"),
          name: "demo",
          sourcePath: ".factory/skills/demo",
        },
        { factoryDir: repo.path(".factory") },
      );

      expect(result.problems).toEqual([]);
      expect(result.files.find((file) => file.path === "data.bin")!.content).toEqual(invalid);
    } finally {
      await repo.cleanup();
    }
  });

  test("keeps a supporting file that ends at its closing --- byte for byte", async () => {
    // Its closing fence is its last line, so the file has no final newline, and
    // neither writing it as read nor rendering it may add one.
    const exact = "---\nvalue: example\n---";
    const repo = await makeRepo({
      ".factory/skills/demo/SKILL.md":
        "---\nname: demo\ndescription: A demo skill. Use when testing.\n---\n\n# Demo\n",
      ".factory/skills/demo/notes.md": exact,
      ".factory/skills/demo/example.yaml": exact,
      ".factory/skills/demo/example.txt": exact,
    });

    try {
      const demo = {
        dir: repo.path(".factory/skills/demo"),
        name: "demo",
        sourcePath: ".factory/skills/demo",
      };
      const withoutRenderer = await compileSkill(demo, { factoryDir: repo.path(".factory") });
      const withRenderer = await compileSkill(demo, {
        factoryDir: repo.path(".factory"),
        render: async (file) => file.text,
      });

      for (const result of [withoutRenderer, withRenderer]) {
        expect(result.problems).toEqual([]);
        const files = new Map(result.files.map((file) => [file.path, file]));
        for (const name of ["example.txt", "example.yaml", "notes.md"]) {
          expect(files.get(name)!.content.toString("utf8"), name).toBe(exact);
        }
      }
    } finally {
      await repo.cleanup();
    }
  });

  test.skipIf(process.platform === "win32")(
    "sets an explicit mode for every file from its executable bit",
    async () => {
      const result = await compileSkill(source, { factoryDir: fixture });
      const files = new Map(result.files.map((file) => [file.path, file]));

      expect(files.get("run.sh")!.mode).toBe(0o755);
      expect(files.get("notes.txt")!.mode).toBe(0o644);
    },
  );

  test("uses the supplied comment for the built-in skill", async () => {
    const result = await compileSkill(
      { dir: fixture, name: "metafab", sourcePath: "resources/metafab-skill" },
      { factoryDir: fixture, comment: builtinComment("9.9.9") },
    );

    expect(result.problems).toEqual([]);
    expect(result.files[0]!.content.toString("utf8")).toContain(
      "---\n<!-- Generated by metafab build 9.9.9. Do not edit. Run metafab build to update. -->\n",
    );
  });

  test("copies a symlink that stays inside .factory", async () => {
    const repo = await makeRepo({
      ".factory/shared/target.md": "shared content\n",
      ".factory/skills/demo/SKILL.md":
        "---\nname: demo\ndescription: A demo skill. Use when testing symlinks.\n---\n\n# Demo\n",
    });

    try {
      await symlink(
        "../../shared/target.md",
        repo.path(".factory/skills/demo/linked.md"),
      );

      const result = await compileSkill(
        {
          dir: repo.path(".factory/skills/demo"),
          name: "demo",
          sourcePath: ".factory/skills/demo",
        },
        { factoryDir: repo.path(".factory") },
      );

      expect(result.problems).toEqual([]);
      const linked = result.files.find((file) => file.path === "linked.md");
      expect(linked?.content.toString("utf8")).toBe("shared content\n");
    } finally {
      await repo.cleanup();
    }
  });

  test("reports a symlink that leaves .factory", async () => {
    const repo = await makeRepo({
      "outside.txt": "outside\n",
      ".factory/skills/demo/SKILL.md":
        "---\nname: demo\ndescription: A demo skill. Use when testing symlinks.\n---\n\n# Demo\n",
    });

    try {
      await symlink("../../../outside.txt", repo.path(".factory/skills/demo/outside.md"));

      const result = await compileSkill(
        {
          dir: repo.path(".factory/skills/demo"),
          name: "demo",
          sourcePath: ".factory/skills/demo",
        },
        { factoryDir: repo.path(".factory") },
      );

      expect(result.files.some((file) => file.path === "outside.md")).toBe(false);
      expect(result.problems).toHaveLength(1);
      expect(result.problems[0]!.file).toBe(".factory/skills/demo/outside.md");
      expect(result.problems[0]!.message).toContain("outside .factory/");
    } finally {
      await repo.cleanup();
    }
  });

  test("copies a symlink into a listed link root", async () => {
    const repo = await makeRepo({
      ".factory/shared/target.md": "shared content\n",
      ".claude/skills/demo/SKILL.md":
        "---\nname: demo\ndescription: A demo skill. Use when testing symlinks.\n---\n\n# Demo\n",
    });

    try {
      await symlink(
        "../../../.factory/shared/target.md",
        repo.path(".claude/skills/demo/linked.md"),
      );

      const source = {
        dir: repo.path(".claude/skills/demo"),
        name: "demo",
        sourcePath: ".claude/skills/demo",
      };

      const refused = await compileSkill(source, { factoryDir: source.dir });

      expect(refused.files.some((file) => file.path === "linked.md")).toBe(false);
      expect(refused.problems).toHaveLength(1);
      expect(refused.problems[0]!.message).toContain("outside .factory/");

      const result = await compileSkill(source, {
        factoryDir: source.dir,
        linkRoots: [repo.path(".factory")],
      });

      expect(result.problems).toEqual([]);
      const linked = result.files.find((file) => file.path === "linked.md");
      expect(linked?.content.toString("utf8")).toBe("shared content\n");
    } finally {
      await repo.cleanup();
    }
  });

  test("copies two directory symlinks to the same target", async () => {
    const repo = await makeRepo({
      ".factory/shared/target.md": "shared content\n",
      ".factory/skills/demo/SKILL.md":
        "---\nname: demo\ndescription: A demo skill. Use when testing symlinks.\n---\n\n# Demo\n",
    });

    try {
      await symlink("../../shared", repo.path(".factory/skills/demo/a"));
      await symlink("../../shared", repo.path(".factory/skills/demo/b"));

      const result = await compileSkill(
        {
          dir: repo.path(".factory/skills/demo"),
          name: "demo",
          sourcePath: ".factory/skills/demo",
        },
        { factoryDir: repo.path(".factory") },
      );

      expect(result.problems).toEqual([]);
      expect(result.files.map((file) => file.path)).toEqual([
        "SKILL.md",
        "a/target.md",
        "b/target.md",
      ]);
      expect(
        result.files.find((file) => file.path === "a/target.md")!.content.toString("utf8"),
      ).toBe("shared content\n");
      expect(
        result.files.find((file) => file.path === "b/target.md")!.content.toString("utf8"),
      ).toBe("shared content\n");
    } finally {
      await repo.cleanup();
    }
  });

  test("reports a directory symlink that points to an ancestor", async () => {
    const repo = await makeRepo({
      ".factory/skills/demo/SKILL.md":
        "---\nname: demo\ndescription: A demo skill. Use when testing symlinks.\n---\n\n# Demo\n",
    });

    try {
      await symlink(".", repo.path(".factory/skills/demo/loop"));

      const result = await compileSkill(
        {
          dir: repo.path(".factory/skills/demo"),
          name: "demo",
          sourcePath: ".factory/skills/demo",
        },
        { factoryDir: repo.path(".factory") },
      );

      expect(result.problems).toHaveLength(1);
      expect(result.problems[0]!.message).toContain("creates a loop");
    } finally {
      await repo.cleanup();
    }
  });

  test("reports a missing SKILL.md", async () => {
    const repo = await makeRepo({ ".factory/skills/demo/notes.md": "notes\n" });

    try {
      const result = await compileSkill(
        {
          dir: repo.path(".factory/skills/demo"),
          name: "demo",
          sourcePath: ".factory/skills/demo",
        },
        { factoryDir: repo.path(".factory") },
      );

      expect(result.problems[0]!.message).toContain("Missing SKILL.md");
    } finally {
      await repo.cleanup();
    }
  });
});

describe("isOwned", () => {
  test("is true only when SKILL.md carries the generated comment", async () => {
    const repo = await makeRepo({
      "owned/SKILL.md":
        "---\nname: owned\ndescription: Owned.\n---\n<!-- Generated by metafab build from .factory/owned/. Edit the source, then run metafab build. -->\n",
      "plain/SKILL.md": "---\nname: plain\ndescription: Plain.\n---\n\n# Plain\n",
    });

    try {
      expect(await isOwned(repo.path("owned"))).toBe(true);
      expect(await isOwned(repo.path("plain"))).toBe(false);
      expect(await isOwned(repo.path("missing"))).toBe(false);
    } finally {
      await repo.cleanup();
    }
  });

  test("is false after a hand edit removes the generated comment", async () => {
    const repo = await makeRepo({});

    try {
      await writeRepoFiles(repo.root, {
        "skill/SKILL.md": "---\nname: skill\ndescription: Edited.\n---\n\n# Skill\n",
      });
      expect(await isOwned(repo.path("skill"))).toBe(false);
    } finally {
      await repo.cleanup();
    }
  });
});

describe("dedupeReadErrors", () => {
  const directoryProblem: Problem = {
    level: "error",
    file: ".factory",
    line: 1,
    message: "Cannot read directory .factory",
    fix: "Check its permissions or restore the directory",
  };
  const childProblem: Problem = {
    level: "error",
    file: ".factory/factory.yaml",
    line: 1,
    message: "Cannot read file .factory/factory.yaml",
    fix: "Check its permissions or restore the file",
  };

  test("an unreadable directory explains the paths below it in any order", () => {
    expect(dedupeReadErrors([directoryProblem, childProblem])).toEqual([directoryProblem]);
    expect(dedupeReadErrors([childProblem, directoryProblem])).toEqual([directoryProblem]);
  });

  test("keeps one read error per path, even when the wording differs", () => {
    const samePath: Problem = {
      level: "error",
      file: ".factory",
      line: 1,
      message: "Cannot read .factory",
      fix: "Check its permissions",
    };

    expect(dedupeReadErrors([directoryProblem, samePath])).toEqual([directoryProblem]);
    expect(dedupeReadErrors([samePath, directoryProblem])).toEqual([samePath]);
    expect(dedupeReadErrors([childProblem, childProblem])).toEqual([childProblem]);
  });

  test("passes problems that are not read errors through unchanged", () => {
    const warning: Problem = {
      level: "warning",
      file: ".factory",
      line: 1,
      message: "Build output not checked: fix the errors above first",
    };

    expect(dedupeReadErrors([warning, childProblem, directoryProblem])).toEqual([
      warning,
      directoryProblem,
    ]);
  });
});

describe("built-in metafab-automations skill", () => {
  const builtin = {
    dir: fileURLToPath(
      new URL("../../../resources/metafab-automations-skill", import.meta.url),
    ),
    name: "metafab-automations",
    sourcePath: "resources/metafab-automations-skill",
  };

  test("holds the Orca sync and the Amp procedure an agent applies", async () => {
    const result = await compileSkill(builtin, {
      factoryDir: builtin.dir,
      comment: builtinComment("1.0.0"),
    });
    const skill = result.files.find((file) => file.path === "SKILL.md")!.content.toString("utf8");

    expect(result.problems).toEqual([]);

    // Orca is one command pair, through the dry run first.
    expect(skill).toContain("metafab automations sync orca --dry-run");
    expect(skill).toContain("then run it without `--dry-run`");
    expect(skill).toContain("`--agent`");

    // The seven steps of the Amp procedure, and the set they apply.
    for (const step of [
      "1. **Read the desired set.**",
      "2. **Read what is installed.**",
      "3. **Put the holding threads under one parent.**",
      "4. **Create the missing ones.**",
      "5. **Update the ones that differ.**",
      "6. **Clear the ones that are gone.**",
      "7. **Report the diff, and nothing else.**",
    ]) {
      expect(skill).toContain(step);
    }
    expect(skill).toContain("metafab automations plan amp --branch <trunk> --json");
    expect(skill).toContain("read `.entries`");

    // The five checks that make a schedule this procedure's to change.
    for (const check of [
      "its title starts with `automation: `",
      "it is a recurring schedule, not an event trigger",
      "its holding thread belongs to the Amp project for `<repo>`",
      "its saved prompt, read with `get_schedule` and its `schedule_id`",
      "its holding thread's title is exactly the schedule's title",
    ]) {
      expect(skill).toContain(check);
    }

    // Every schedule call names the schedule and the thread that holds it, because
    // one thread can hold several.
    expect(skill).toContain("read with `get_schedule` and its `schedule_id`");
    expect(skill).toContain(
      "update it with `update_schedule`, its `schedule_id` and its holding `thread`",
    );
    expect(skill).toContain(
      "clear it with `clear_schedule`, its `schedule_id` and its holding `thread`",
    );
    expect(skill).toContain('never relies on a thread\'s "only schedule"');

    // A holding thread proves which factory owns it after its schedule is gone.
    expect(skill).toContain(
      "This thread holds the `automation: <name>` schedule of the `<factory>` factory for metafab automations sync. Do nothing and end.",
    );
    expect(skill).toContain("Run the factory automation `<name>` from the `<factory>` factory.");
    expect(skill).toContain(
      "This thread holds the factory automation holding threads for metafab automations sync. Do nothing and end.",
    );

    // Step 4 finds an empty holding thread anywhere in the project, not only under the parent.
    expect(skill).toContain('`"automation: <name>" author:me archived:false repo:<repo>`');
    expect(skill).toContain("wherever it sits");

    // Step 6's three retire cases, and the archive order it may not shortcut.
    expect(skill).toContain("When it still holds another schedule");
    expect(skill).toContain("has a run in progress");
    expect(skill).toContain("archive each unarchived child");
    expect(skill).not.toContain("stop_running_turn");
    expect(skill).not.toContain("keep_child_threads");

    // The report lines a person reads.
    expect(skill).toContain("`left alone: <title>`");
    expect(skill).toContain("`kept:");
    expect(skill).toContain("`no changes`");

    // The rules, and what an unattended run is allowed to do.
    expect(skill).toContain("### Rules");
    expect(skill).toContain("**Only managed schedules are this procedure's to change.**");
    expect(skill).toContain("**A second run in a row changes nothing.**");
    expect(skill).toContain("### Unattended runs");
    expect(skill).toContain("that body is the owner's standing, explicit request");
  });
});

