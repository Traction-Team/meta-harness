import { loadFactory } from "../../../src/core/factory/index.js";
import { copyFileWithMode, listFiles, pathExists } from "../../../src/util/fs.js";
import { isolateGitConfig } from "../hooks/helpers.js";
import { makeRepo } from "../../helpers/makeRepo.js";
import type { RepoFiles, TempRepo } from "../../helpers/makeRepo.js";

const require = createRequire(import.meta.url);
const PACKAGE_VERSION = (require("../../../package.json") as { version: string }).version;

const FIXTURE = fileURLToPath(new URL("../../fixtures/env/build", import.meta.url));

const GENERATED = (source: string): string =>
  `<!-- Generated by metafab build from ${source}/. Edit the source, then run metafab build. -->`;

const repos: TempRepo[] = [];

function track(repo: TempRepo): TempRepo {
  repos.push(repo);
  return repo;
}

afterEach(async () => {
  await Promise.all(repos.splice(0).map((repo) => repo.cleanup()));
});

/** Copies the format 2 build fixture into a Git repository. */
async function fixtureRepo(): Promise<TempRepo> {
  const repo = track(await makeRepo({}, { git: true }));
  for (const relative of await listFiles(FIXTURE)) {
    await copyFileWithMode(
      path.join(FIXTURE, ...relative.split("/")),
      repo.path(...relative.split("/")),
    );
  }
  return repo;
}

/** Builds with the selection `--env` would give; without one, every value. */
async function build(
  root: string,
  env?: readonly string[],
): Promise<{ plan: BuildPlan; report: BuildReport }> {
  const factory = await loadFactory(root);
  const config = await loadConfig(factory.dir);
  const selection = await resolveSelection(factory.factoryYaml?.env ?? [], {
    root,
    options: env,
    processEnv: {},
  });
  const plan = await planBuild(factory, config, PACKAGE_VERSION, { selection });
  const report = await applyBuild(plan);
  return { plan, report };
}

const SKILL_HEADER = ["---", "name: hello", "description: Hello. Use when testing.", "---"].join("\n");

function skillSource(body: string): string {
  return `${SKILL_HEADER}\n${body}`;
}

describe("build with directives", () => {
  let isolation: Awaited<ReturnType<typeof isolateGitConfig>>;

  beforeEach(async () => {
    isolation = await isolateGitConfig();
  });

  afterEach(() => {
    isolation.restore();
  });

  test("renders SKILL.md below its frontmatter and a supporting Markdown file", async () => {
    const repo = await fixtureRepo();

    const { plan } = await build(repo.root, ["harness=amp"]);

    expect(plan.errors).toEqual([]);
    expect(plan.conflicts).toEqual([]);

    expect(await readFile(repo.path(".agents/skills/hello/SKILL.md"), "utf8")).toBe(
      [
        "---",
        "name: hello",
        "description: Say hello. Use when testing the build.",
        "---",
        GENERATED(".factory/skills/hello"),
        "",
        "# Hello",
        "",
        "Start an Amp thread and run the skill there.",
        "",
        "**When workspace is orca:**",
        "On Orca, the thread runs in its own worktree.",
        "",
      ].join("\n"),
    );

    expect(await readFile(repo.path(".agents/skills/hello/notes.md"), "utf8")).toBe(
      [
        "# Notes",
        "",
        "Amp threads keep their own workspace.",
        "",
        "Everything else applies everywhere.",
        "",
      ].join("\n"),
    );
  });

  test("installs a partially matching skill with its label, then removes it when it does not match", async () => {
    const repo = await fixtureRepo();

    const partial = await build(repo.root);
    expect(partial.plan.errors).toEqual([]);

    expect(await readFile(repo.path(".agents/skills/amp-threads/SKILL.md"), "utf8")).toBe(
      [
        "---",
        "name: amp-threads",
        "description: Work in Amp threads. Use when the harness is Amp.",
        "---",
        GENERATED(".factory/skills/amp-threads"),
        "**Applies only In Amp.**",
        "",
        "# Amp threads",
        "",
        "Read the thread before you start.",
        "",
      ].join("\n"),
    );

    const removed = await build(repo.root, ["harness=opencode"]);

    expect(removed.plan.errors).toEqual([]);
    expect(removed.report.changed).toContainEqual({
      path: ".agents/skills/amp-threads",
      action: "removed",
    });
    expect(await pathExists(repo.path(".agents/skills/amp-threads"))).toBe(false);
  });

  test("renders the root AGENTS.md block for every value, the same for every selection", async () => {
    const repo = await fixtureRepo();
    const blocks: string[] = [];

    for (const env of [
      ["harness=amp"],
      ["harness=claude"],
      ["harness=opencode", "workspace=orca"],
    ]) {
      const { plan } = await build(repo.root, env);
      expect(plan.errors).toEqual([]);
      blocks.push(await readFile(repo.path("AGENTS.md"), "utf8"));
    }

    const expected = [
      "<!-- factory:start -->",
      GENERATED(".factory"),
      "",
      "# Demo factory",
      "",
      "Build and review work in slices.",
      "",
      "**In Amp:**",
      "Run metafab build with `--env harness=amp` before opening a thread.",
      "",
      "**When workspace is orca:**",
      "Orca starts each worktree with a setup script.",
      "**When workspace is orb:**",
      "An orb starts from a clean checkout.",
      "",
      "## Factory source",
      "",
      "This repository stores its factory in `.factory/`. Edit that directory and run `metafab build`.",
      "Do not edit installed copies in `.claude/` or `.agents/`.",
      "<!-- factory:end -->",
      "",
    ].join("\n");

    expect(blocks).toEqual([expected, expected, expected]);
  });

  test("counts the rendered block against the AGENTS.md line limit", async () => {
    // One partial `when` block loses its two directive lines and gains a label
    // line, so the rendered block is one line shorter than the source.
    async function blockWarnings(plain: number): Promise<BuildPlan["warnings"]> {
      const standing = [
        ...Array.from({ length: plain }, (_, index) => `- rule ${index + 1}`),
        "<!-- factory:when env.harness == amp -->",
        "Amp.",
        "<!-- factory:endwhen -->",
        "",
      ].join("\n");
      const repo = track(
        await makeRepo({
          ".factory/factory.yaml":
            "format: 2\nname: demo\nenv:\n  harness: { values: [opencode, claude, amp] }\n",
          ".factory/metafab.yaml": "agents: [codex]\nmetafab-skill: false\n",
          ".factory/AGENTS.md": standing,
        }),
      );

      const { plan } = await build(repo.root);
      expect(plan.errors).toEqual([]);
      return plan.warnings;
    }

    // 289 rules + 3 block lines render to 291 lines, so the block is 300 lines.
    expect(await blockWarnings(289)).toEqual([]);

    // One more rule makes the rendered block 301 lines.
    expect(await blockWarnings(290)).toEqual([
      {
        level: "warning",
        file: "AGENTS.md",
        message: "The generated AGENTS.md block is 301 lines; the limit is 300",
        fix: "Move detail into .factory/AGENTS.md sections and keep the root block short",
      },
    ]);
  });

  test("copies directives as text in a format 1 factory", async () => {
    const body = [
      "",
      "# Hello",
      "",
      "<!-- factory:when env.harness == amp -->",
      "Amp only.",
      "<!-- factory:endwhen -->",
      "",
    ].join("\n");
    const standing = "<!-- factory:when env.harness == amp -->\nAmp only.\n<!-- factory:endwhen -->\n";
    const repo = track(
      await makeRepo({
        ".factory/factory.yaml": "format: 1\nname: demo\n",
        ".factory/metafab.yaml": "agents: [codex]\nmetafab-skill: false\n",
        ".factory/AGENTS.md": standing,
        ".factory/skills/hello/SKILL.md": skillSource(body),
      }),
    );

    const { plan } = await build(repo.root);

    expect(plan.errors).toEqual([]);
    expect(await readFile(repo.path(".agents/skills/hello/SKILL.md"), "utf8")).toBe(
      `${SKILL_HEADER}\n${GENERATED(".factory/skills/hello")}\n${body}`,
    );
    expect(await readFile(repo.path("AGENTS.md"), "utf8")).toContain(`${standing}\n## Factory source`);
  });

  test("a second build with the same selection is up to date", async () => {
    const repo = await fixtureRepo();

    const first = await build(repo.root, ["harness=amp", "workspace=orca"]);
    expect(first.plan.errors).toEqual([]);
    expect(first.report.changed.length).toBeGreaterThan(0);

    const second = await build(repo.root, ["harness=amp", "workspace=orca"]);
    expect(second.plan.errors).toEqual([]);
    expect(second.report.changed).toEqual([]);
  });

  test("does not render a document that has problems", async () => {
    const repo = track(
      await makeRepo({
        ".factory/factory.yaml": "format: 2\nname: demo\nenv:\n  harness: { values: [amp] }\n",
        ".factory/metafab.yaml": "agents: [codex]\nmetafab-skill: false\n",
        ".factory/skills/hello/SKILL.md": skillSource(
          "\n# Hello\n\n<!-- factory:when env.harness == amp -->\nNever closed.\n",
        ),
      }),
    );

    const { plan, report } = await build(repo.root, ["harness=amp"]);

    expect(plan.errors).toEqual([
      {
        level: "error",
        file: ".factory/skills/hello/SKILL.md",
        line: 8,
        message: "factory:when on line 8 is never closed in this file",
        fix: "Add <!-- factory:endwhen --> in the same file",
      },
    ]);
    expect(report.changed).toEqual([]);
    expect(await pathExists(repo.path(".agents/skills/hello"))).toBe(false);
  });

  test("renders a document whose only problem is a warning, keeping the fenced directives as text", async () => {
    // The fence is never closed, so `check` warns that the directive lines after
    // it are text. That warning must not stop the rest of the document rendering.
    const body = [
      "",
      "# Hello",
      "",
      "<!-- factory:when env.harness == amp -->",
      "AMP ONLY.",
      "<!-- factory:endwhen -->",
      "```text",
      "<!-- factory:when env.harness == amp -->",
      "",
    ].join("\n");
    const standing = [
      "<!-- factory:when env.harness == amp -->",
      "Amp only.",
      "<!-- factory:endwhen -->",
      "```text",
      "<!-- factory:when env.harness == amp -->",
      "",
    ].join("\n");
    const repo = track(
      await makeRepo({
        ".factory/factory.yaml":
          "format: 2\nname: demo\nenv:\n  harness: { values: [amp, claude] }\n",
        ".factory/metafab.yaml": "agents: [codex]\nmetafab-skill: false\n",
        ".factory/AGENTS.md": standing,
        ".factory/skills/hello/SKILL.md": skillSource(body),
      }),
    );

    const { plan } = await build(repo.root, ["harness=claude"]);

    expect(plan.errors).toEqual([]);
    expect(await readFile(repo.path(".agents/skills/hello/SKILL.md"), "utf8")).toBe(
      [
        SKILL_HEADER,
        GENERATED(".factory/skills/hello"),
        "",
        "# Hello",
        "",
        "```text",
        "<!-- factory:when env.harness == amp -->",
        "",
      ].join("\n"),
    );

    // The root block renders for every value, so the same block keeps its label.
    const root = await readFile(repo.path("AGENTS.md"), "utf8");
    expect(root).toContain(
      [
        "**When harness is amp:**",
        "Amp only.",
        "```text",
        "<!-- factory:when env.harness == amp -->",
      ].join("\n"),
    );
  });

  test("renders a supporting file's body when its frontmatter contains a code fence", async () => {
    // A fence opened in frontmatter must not reach the body: validation parses
    // the body alone, so rendering splits at the same `---` boundary.
    const notes = [
      "---",
      "example: |",
      "  ```sh",
      "---",
      "<!-- factory:when env.harness == amp -->",
      "AMP ONLY.",
      "<!-- factory:endwhen -->",
      "",
      "Everywhere.",
      "",
    ].join("\n");
    const repo = track(
      await makeRepo({
        ".factory/factory.yaml":
          "format: 2\nname: demo\nenv:\n  harness: { values: [amp, claude] }\n",
        ".factory/metafab.yaml": "agents: [codex]\nmetafab-skill: false\n",
        ".factory/skills/hello/SKILL.md": skillSource("\n# Hello\n"),
        ".factory/skills/hello/notes.md": notes,
      }),
    );

    const { plan } = await build(repo.root, ["harness=claude"]);

    expect(plan.errors).toEqual([]);
    expect(await readFile(repo.path(".agents/skills/hello/notes.md"), "utf8")).toBe(
      ["---", "example: |", "  ```sh", "---", "", "Everywhere.", ""].join("\n"),
    );
  });

  test("renders a factory with eleven variables whose blocks each name one", async () => {
    const names = Array.from({ length: 11 }, (_, index) => `v${index}`);
    const env = names.map((name) => `  ${name}: { values: [one, two] }`).join("\n");
    const body = [
      "",
      "# Hello",
      "",
      ...names.flatMap((name) => [
        `<!-- factory:when env.${name} == one -->`,
        `${name} is one.`,
        "<!-- factory:endwhen -->",
        "",
      ]),
    ].join("\n");
    const repo = track(
      await makeRepo({
        ".factory/factory.yaml": `format: 2\nname: demo\nenv:\n${env}\n`,
        ".factory/metafab.yaml": "agents: [codex]\nmetafab-skill: false\n",
        ".factory/skills/hello/SKILL.md": skillSource(body),
      }),
    );

    const { plan } = await build(repo.root);

    expect(plan.errors).toEqual([]);
    const installed = await readFile(repo.path(".agents/skills/hello/SKILL.md"), "utf8");
    // Every block applies in some of the two values, so each keeps its label.
    expect(installed).toContain("**When v0 is one:**\nv0 is one.");
    expect(installed).toContain("**When v10 is one:**\nv10 is one.");
  });
});
