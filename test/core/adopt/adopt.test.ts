import { chmod, readFile, readdir, stat } from "node:fs/promises";
import { afterEach, describe, expect, test } from "vitest";
import {
  ADOPTION_DESCRIPTION,
  ADOPTION_QUESTION,
  adoptionRequired,
  applyAdoption,
  describeAdoption,
  planAdoption,
} from "../../../src/core/adopt.js";
import type { AdoptionPlan } from "../../../src/core/adopt.js";
import { loadFactory } from "../../../src/core/factory/load.js";
import { pathExists } from "../../../src/util/fs.js";
import { makeRepo } from "../../helpers/makeRepo.js";
import type { TempRepo } from "../../helpers/makeRepo.js";

const DESTINATIONS = [".claude/skills", ".agents/skills"];
const QUESTION = "Metafab manages installed skill directories as generated output. Move existing repository skills into `.factory/skills/` and ignore the generated copies?";

const repos: TempRepo[] = [];

afterEach(async () => {
  await Promise.all(repos.splice(0).map((repo) => repo.cleanup()));
});

async function repoWith(files: Record<string, string> = {}): Promise<TempRepo> {
  const repo = await makeRepo(files);
  repos.push(repo);
  return repo;
}

function skill(name: string, description = `Use ${name} when the task needs it.`): string {
  return `---\nname: ${name}\ndescription: ${description}\n---\n\n# ${name}\n`;
}

function ownedSkill(name: string): string {
  return `---\nname: ${name}\ndescription: Use ${name}.\n---\n<!-- Generated by metafab build from .factory/skills/${name}/. Edit the source, then run metafab build. -->\n\n# ${name}\n`;
}

describe("planAdoption", () => {
  test("returns no moves or blockers when the destinations are absent", async () => {
    const repo = await repoWith();

    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    expect(plan).toEqual({ root: repo.root, moves: [], blockers: [] });
  });

  test("moves a valid skill from one destination", async () => {
    const repo = await repoWith({ ".claude/skills/release/SKILL.md": skill("release") });

    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    expect(plan.blockers).toEqual([]);
    expect(plan.moves).toEqual([
      {
        name: "release",
        from: [".claude/skills/release"],
        to: ".factory/skills/release",
      },
    ]);
  });

  test("moves identical copies from both destinations once", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": skill("release"),
      ".agents/skills/release/SKILL.md": skill("release"),
    });

    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    expect(plan.blockers).toEqual([]);
    expect(plan.moves).toEqual([
      {
        name: "release",
        from: [".agents/skills/release", ".claude/skills/release"],
        to: ".factory/skills/release",
      },
    ]);
  });

  test("blocks copies that differ", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": skill("release"),
      ".agents/skills/release/SKILL.md": skill("release", "A different description."),
    });

    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    expect(plan.moves).toEqual([]);
    expect(plan.blockers).toHaveLength(1);
    expect(plan.blockers[0]!.message).toBe(
      'Skill "release" differs between .agents/skills/release and .claude/skills/release',
    );
    expect(plan.blockers[0]!.file).toBe(".claude/skills/release");
  });

  test("blocks a stray file", async () => {
    const repo = await repoWith({ ".claude/skills/notes.txt": "notes\n" });

    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    expect(plan.moves).toEqual([]);
    expect(plan.blockers).toHaveLength(1);
    expect(plan.blockers[0]!.file).toBe(".claude/skills/notes.txt");
    expect(plan.blockers[0]!.message).toBe(
      "Unowned file .claude/skills/notes.txt is not part of a valid skill",
    );
  });

  test("blocks a directory without SKILL.md", async () => {
    const repo = await repoWith({ ".claude/skills/release/README.md": "# Release\n" });

    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    expect(plan.moves).toEqual([]);
    expect(plan.blockers).toHaveLength(1);
    expect(plan.blockers[0]!.file).toBe(".claude/skills/release");
    expect(plan.blockers[0]!.message).toBe(
      "Unowned directory .claude/skills/release is not part of a valid skill",
    );
  });

  test("blocks a SKILL.md without valid frontmatter", async () => {
    const repo = await repoWith({ ".claude/skills/release/SKILL.md": "# Release\n" });

    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    expect(plan.moves).toEqual([]);
    expect(plan.blockers).toHaveLength(1);
    expect(plan.blockers[0]!.file).toBe(".claude/skills/release/SKILL.md");
    expect(plan.blockers[0]!.message).toContain("is not part of a valid skill");
  });

  test("blocks a name that already exists in the factory", async () => {
    const repo = await repoWith({
      ".factory/skills/release/SKILL.md": skill("release"),
      ".claude/skills/release/SKILL.md": skill("release"),
    });
    const factory = await loadFactory(repo.root);

    const plan = await planAdoption(repo.root, DESTINATIONS, factory);

    expect(plan.moves).toEqual([]);
    expect(plan.blockers).toHaveLength(1);
    expect(plan.blockers[0]!.file).toBe(".claude/skills/release");
    expect(plan.blockers[0]!.message).toBe('Skill "release" already exists in .factory/');
  });

  test("blocks a name that already exists in the factory at another path", async () => {
    const repo = await repoWith({
      ".factory/workflows/release/SKILL.md": skill("release"),
      ".claude/skills/release/SKILL.md": skill("release"),
    });
    const factory = await loadFactory(repo.root);

    const plan = await planAdoption(repo.root, DESTINATIONS, factory);

    expect(plan.moves).toEqual([]);
    expect(plan.blockers[0]!.message).toBe('Skill "release" already exists in .factory/');
  });

  test("blocks a name that already exists in the incoming fab", async () => {
    const repo = await repoWith({ ".claude/skills/release/SKILL.md": skill("release") });

    const plan = await planAdoption(repo.root, DESTINATIONS, undefined, ["release"]);

    expect(plan.moves).toEqual([]);
    expect(plan.blockers).toHaveLength(1);
    expect(plan.blockers[0]!.message).toBe('Skill "release" already exists in the incoming fab');
  });

  test("does not treat owned directories as candidates", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": ownedSkill("release"),
      ".agents/skills/release/SKILL.md": ownedSkill("release"),
    });

    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    expect(plan).toEqual({ root: repo.root, moves: [], blockers: [] });
  });

  test("adopts an unowned skill beside an owned one", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": skill("release"),
      ".claude/skills/metafab/SKILL.md": ownedSkill("metafab"),
    });

    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    expect(plan.blockers).toEqual([]);
    expect(plan.moves.map((move) => move.name)).toEqual(["release"]);
  });

  test("blocks a directory whose name is not a valid skill name", async () => {
    const repo = await repoWith({ ".claude/skills/Release_Notes/SKILL.md": skill("Release_Notes") });

    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    expect(plan.moves).toEqual([]);
    expect(plan.blockers).toHaveLength(1);
    expect(plan.blockers[0]!.message).toBe(
      'Skill name "Release_Notes" is not a valid Agent Skill name',
    );
  });

  test("blocks a destination that is a file", async () => {
    const repo = await repoWith({ ".claude/skills": "not a directory\n" });

    const plan = await planAdoption(repo.root, [".claude/skills"], undefined);

    expect(plan.moves).toEqual([]);
    expect(plan.blockers[0]!.message).toBe(".claude/skills is a file, not a directory");
  });

  test("reports blockers in a stable order", async () => {
    const repo = await repoWith({
      ".claude/skills/zeta/README.md": "# Zeta\n",
      ".agents/skills/alpha.txt": "notes\n",
    });

    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    expect(plan.blockers.map((problem) => problem.file)).toEqual([
      ".agents/skills/alpha.txt",
      ".claude/skills/zeta",
    ]);
  });
});

describe("applyAdoption", () => {
  test("moves the whole skill tree and keeps file modes", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": skill("release"),
      ".claude/skills/release/reference/notes.md": "notes\n",
      ".claude/skills/release/scripts/run.sh": "#!/bin/sh\necho release\n",
    });
    await chmod(repo.path(".claude/skills/release/scripts/run.sh"), 0o755);
    const plan = await planAdoption(repo.root, [".claude/skills"], undefined);

    await applyAdoption(plan);

    expect(await pathExists(repo.path(".claude/skills/release"))).toBe(false);
    expect(await readFile(repo.path(".factory/skills/release/SKILL.md"), "utf8")).toBe(
      skill("release"),
    );
    expect(await readFile(repo.path(".factory/skills/release/reference/notes.md"), "utf8")).toBe(
      "notes\n",
    );
    expect((await stat(repo.path(".factory/skills/release/scripts/run.sh"))).mode & 0o111).not.toBe(0);
    expect(await readdir(repo.path(".factory/skills"))).toEqual(["release"]);
  });

  test("moves identical copies once and deletes the duplicate", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": skill("release"),
      ".agents/skills/release/SKILL.md": skill("release"),
    });
    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    await applyAdoption(plan);

    expect(await pathExists(repo.path(".claude/skills/release"))).toBe(false);
    expect(await pathExists(repo.path(".agents/skills/release"))).toBe(false);
    expect(await readFile(repo.path(".factory/skills/release/SKILL.md"), "utf8")).toBe(
      skill("release"),
    );
  });

  test("applies only moves and leaves unowned output alone", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": skill("release"),
      ".claude/skills/metafab/SKILL.md": ownedSkill("metafab"),
    });
    const plan = await planAdoption(repo.root, [".claude/skills"], undefined);

    await applyAdoption(plan);

    expect(await pathExists(repo.path(".factory/skills/release"))).toBe(true);
    expect(await pathExists(repo.path(".claude/skills/metafab/SKILL.md"))).toBe(true);
  });

  test("refuses a plan with blockers and changes nothing", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": skill("release"),
      ".claude/skills/notes.txt": "notes\n",
    });
    const plan = await planAdoption(repo.root, [".claude/skills"], undefined);

    await expect(applyAdoption(plan)).rejects.toThrow("Adoption is blocked by 1 entry.");

    expect(await pathExists(repo.path(".claude/skills/release/SKILL.md"))).toBe(true);
    expect(await pathExists(repo.path(".factory/skills"))).toBe(false);
  });
});

describe("consent helpers", () => {
  test("the question matches the specification", () => {
    expect(ADOPTION_QUESTION).toBe(QUESTION);
  });

  test("the required payload names --adopt and lists the moves", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": skill("release"),
      ".agents/skills/release/SKILL.md": skill("release"),
    });
    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    const required = adoptionRequired(plan);

    expect(required.name).toBe("adopt");
    expect(required.flag).toBe("--adopt");
    expect(required.description).toBe(ADOPTION_DESCRIPTION);
    expect(required.moves).toEqual(plan.moves);
  });

  test("describes every move on its own line", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": skill("release"),
      ".claude/skills/review/SKILL.md": skill("review"),
    });
    const plan = await planAdoption(repo.root, [".claude/skills"], undefined);

    expect(describeAdoption(plan)).toBe(
      "release: .claude/skills/release -> .factory/skills/release\nreview: .claude/skills/review -> .factory/skills/review",
    );
  });

  test("describes nothing for an empty plan", () => {
    const plan: AdoptionPlan = { root: "/tmp/nowhere", moves: [], blockers: [] };

    expect(describeAdoption(plan)).toBe("");
  });
});
