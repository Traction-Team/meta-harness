describe("applyAdoption", () => {
  test("moves the whole skill tree and keeps file modes", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": skill("release"),
      ".claude/skills/release/reference/notes.md": "notes\n",
      ".claude/skills/release/scripts/run.sh": "#!/bin/sh\necho release\n",
    });
    await chmod(repo.path(".claude/skills/release/scripts/run.sh"), 0o755);
    const plan = await planAdoption(repo.root, [".claude/skills"], undefined);

    await applyAdoption(plan);

    expect(await pathExists(repo.path(".claude/skills/release"))).toBe(false);
    expect(await readFile(repo.path(".factory/skills/release/SKILL.md"), "utf8")).toBe(
      skill("release"),
    );
    expect(await readFile(repo.path(".factory/skills/release/reference/notes.md"), "utf8")).toBe(
      "notes\n",
    );
    if (process.platform !== "win32") {
      const moved = await stat(repo.path(".factory/skills/release/scripts/run.sh"));
      expect(moved.mode & 0o111).not.toBe(0);
    }
    expect(await readdir(repo.path(".factory/skills"))).toEqual(["release"]);
  });

  test("moves identical copies once and deletes the duplicate", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": skill("release"),
      ".agents/skills/release/SKILL.md": skill("release"),
    });
    const plan = await planAdoption(repo.root, DESTINATIONS, undefined);

    await applyAdoption(plan);

    expect(await pathExists(repo.path(".claude/skills/release"))).toBe(false);
    expect(await pathExists(repo.path(".agents/skills/release"))).toBe(false);
    expect(await readFile(repo.path(".factory/skills/release/SKILL.md"), "utf8")).toBe(
      skill("release"),
    );
  });

  test("applies only moves and leaves unowned output alone", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": skill("release"),
      ".claude/skills/metafab/SKILL.md": ownedSkill("metafab"),
    });
    const plan = await planAdoption(repo.root, [".claude/skills"], undefined);

    await applyAdoption(plan);

    expect(await pathExists(repo.path(".factory/skills/release"))).toBe(true);
    expect(await pathExists(repo.path(".claude/skills/metafab/SKILL.md"))).toBe(true);
  });

  test("refuses a plan with blockers and changes nothing", async () => {
    const repo = await repoWith({
      ".claude/skills/release/SKILL.md": skill("release"),
      ".claude/skills/notes.txt": "notes\n",
    });
    const plan = await planAdoption(repo.root, [".claude/skills"], undefined);

    await expect(applyAdoption(plan)).rejects.toThrow("Adoption is blocked by 1 entry.");

    expect(await pathExists(repo.path(".claude/skills/release/SKILL.md"))).toBe(true);
    expect(await pathExists(repo.path(".factory/skills"))).toBe(false);
  });

  test("refuses to write through a symlinked .factory/skills", async () => {
    const repo = await repoWith({ ".claude/skills/release/SKILL.md": skill("release") });
    await mkdir(repo.path(".factory"), { recursive: true });
    await mkdir(repo.path("outside"), { recursive: true });
    await symlink("../outside", repo.path(".factory/skills"), "dir");

    const plan: AdoptionPlan = {
      root: repo.root,
      moves: [
        {
          name: "release",
          from: [".claude/skills/release"],
          to: ".factory/skills/release",
        },
      ],
      blockers: [],
    };

    await expect(applyAdoption(plan)).rejects.toThrow(
      "Adoption cannot write into the factory directory.",
    );

    expect(await readdir(repo.path("outside"))).toEqual([]);
    expect(await pathExists(repo.path(".claude/skills/release/SKILL.md"))).toBe(true);
  });
});

