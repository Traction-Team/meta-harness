#!/usr/bin/env node
/**
 * Shows where a feature stands: every plan carrying its code, in code order, with its stage, status, pull request, stack and needs. The plans' frontmatter and the host are the source of truth; the plan table in a feature doc (`<features>/<code>-<slug>.md`) is generated from them, never edited by hand.
 *
 *   node .factory/scripts/feature.mjs                  # every feature, one line each
 *   node .factory/scripts/feature.mjs ONB              # one feature's table
 *   node .factory/scripts/feature.mjs ONB --write      # rewrite the table in its feature doc, between the factory:plans markers
 *   node .factory/scripts/feature.mjs --write          # rewrite every feature doc's table
 *
 * With `features` empty in docs/factory.md there are no feature docs, and the script says so and stops. Stage is the length of the longest `needs` chain inside the feature, so plans in the same stage can be built in parallel once the stage before has merged (or been stacked on). Pull request links come from `gh repo view --json url`, or from the `origin` remote when `gh` is unavailable. A merge conflict in a generated table is resolved by running `--write` again, never by hand.
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, posix } from 'node:path';
import {
  PLAN_DONE,
  ROOT,
  byCode,
  fileSource,
  isFactoryPlan,
  listFeatures,
  listPlans,
  loadFeature,
  loadPlan,
  openPrClaims,
  planBranch,
  readSettings,
  repoPath,
  tryGit,
} from './lib.mjs';

const START = '<!-- factory:plans:start (generated by node .factory/scripts/feature.mjs <code> --write; do not edit by hand) -->';
const START_RE = /<!-- factory:plans:start[^\n]*-->/;
const END = '<!-- factory:plans:end -->';

const args = process.argv.slice(2);
const write = args.includes('--write');
const refIdx = args.indexOf('--ref');
const ref = refIdx >= 0 ? args[refIdx + 1] : undefined;
if (write && ref) {
  console.error('--write rewrites the working tree, so it cannot read another ref');
  process.exit(1);
}
const only = args.find((a, i) => !a.startsWith('--') && args[i - 1] !== '--ref')?.toUpperCase();

const source = fileSource(ref);
const settings = readSettings(source).values;
if (!settings.features) {
  console.log('No feature docs: `features` is empty in docs/factory.md, so plans carry no code.');
  process.exit(0);
}

const plans = [];
for (const rel of listPlans(source, settings)) {
  const plan = loadPlan(source, rel, settings);
  if (isFactoryPlan(plan) && plan.feature) plans.push(plan);
}
const features = new Map();
for (const rel of listFeatures(source, settings)) {
  const feature = loadFeature(source, rel);
  if (feature?.code) features.set(feature.code, feature);
}
if (only && !features.has(only)) {
  console.error(`No feature doc with code ${only}. Features: ${[...features.keys()].join(', ') || 'none'}`);
  process.exit(1);
}

/** The repository's web address, for pull request links. `gh` first, then the `origin` remote, so a clone with no `gh` still links. */
function repoUrl() {
  try {
    const url = JSON.parse(execFileSync('gh', ['repo', 'view', '--json', 'url'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] })).url;
    if (url) return String(url).replace(/\/+$/, '');
  } catch {
    // No `gh`, or not signed in: fall back to the remote.
  }
  const remote = tryGit(['remote', 'get-url', 'origin']);
  if (!remote) return undefined;
  const match = /^(?:git@([^:]+):|(?:ssh|https?):\/\/(?:[^@/]+@)?([^/]+)\/)(.+?)(?:\.git)?$/.exec(remote.trim());
  if (!match) return undefined;
  return `https://${match[1] ?? match[2]}/${match[3]}`;
}
const base = repoUrl();
const prLink = (number) => (base ? `[#${number}](${base}/pull/${number})` : `#${number}`);

/** Every pull request's state by number, from one `gh` call. Undefined when `gh` is unavailable: the table then shows plan statuses only. */
function readPrs() {
  try {
    const raw = execFileSync('gh', ['pr', 'list', '--state', 'all', '--limit', '400', '--json', 'number,state,isDraft,baseRefName,headRefName'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
    return new Map(JSON.parse(raw).map((pr) => [String(pr.number), pr]));
  } catch {
    return undefined;
  }
}
const prs = readPrs();
// A claimed plan's `pr:` is often still empty on the trunk (the claim commit lives on its branch), so the open pull requests' `Plan:` lines fill it in.
const claims = new Map((openPrClaims(settings) ?? []).map((claim) => [claim.plan, claim]));
for (const plan of plans) if (!plan.pr && claims.has(plan.path)) plan.pr = String(claims.get(plan.path).pr);
const byPath = new Map(plans.map((plan) => [plan.path, plan]));
const plansDir = repoPath(settings.plans);
const featuresDir = repoPath(settings.features);
const plansFromFeatures = posix.relative(featuresDir, plansDir);
const short = (path) => path.replace(`${plansDir}/`, '').replace(/\.md$/, '');

function stageOf(plan, seen = new Set()) {
  if (seen.has(plan.path)) return 1;
  seen.add(plan.path);
  const inside = plan.needs.map((need) => byPath.get(need)).filter((need) => need && need.feature === plan.feature);
  return 1 + Math.max(0, ...inside.map((need) => stageOf(need, seen)));
}

function row(plan) {
  const pr = plan.pr ? prs?.get(plan.pr) : undefined;
  const merged = PLAN_DONE.includes(plan.status) || pr?.state === 'MERGED';
  let status = plan.status;
  if (merged) status = PLAN_DONE.includes(plan.status) ? 'merged' : 'merged, not landed';
  else if (pr?.state === 'OPEN') status = pr.isDraft ? 'draft PR' : 'in review';
  else if (pr?.state === 'CLOSED') status = 'PR closed';
  const stackedOn = pr?.state === 'OPEN' && pr.baseRefName !== settings.trunk ? plans.find((p) => p.pr && prs?.get(p.pr)?.headRefName === pr.baseRefName) : undefined;
  const needs = plan.needs.map((need) => byPath.get(need)?.code ?? short(need)).join(', ') || '—';
  const branch = pr?.headRefName ?? planBranch(plan);
  return {
    done: merged,
    cells: [
      merged ? '[x]' : '[ ]',
      `**${plan.code}**`,
      stageOf(plan),
      `[${plan.title.replace(/^[a-z()0-9-]+: /, '').replace(`${plan.code} `, '').replace(/\|/g, '\\|')}](${plansFromFeatures}/${plan.path.split('/').pop()})`,
      status,
      plan.pr ? prLink(plan.pr) : '—',
      stackedOn ? `on ${stackedOn.code}` : pr?.state === 'OPEN' && pr.baseRefName !== settings.trunk ? `on \`${pr.baseRefName}\`` : '—',
      needs,
      `\`${branch}\``,
    ],
  };
}

function table(code) {
  const mine = plans.filter((plan) => plan.feature === code).sort(byCode);
  const rows = mine.map(row);
  const done = rows.filter((r) => r.done).length;
  const lines = [
    `${done} of ${mine.length} plans merged.${prs ? '' : ' (gh unavailable: pull request states not read.)'}`,
    '',
    '| Done | Code | Stage | Plan | Status | PR | Stacked | Needs | Branch |',
    '|---|---|---|---|---|---|---|---|---|',
    ...rows.map((r) => `| ${r.cells.join(' | ')} |`),
  ];
  return { text: lines.join('\n'), done, total: mine.length };
}

const codes = only ? [only] : [...features.keys()].sort();
if (!write && !only) {
  for (const code of codes) {
    const feature = features.get(code);
    const { done, total } = table(code);
    console.log(`${code.padEnd(5)} ${feature.title} · ${feature.status} · ${done} of ${total} plans merged · ${short(feature.path)}.md`);
  }
  if (!codes.length) console.log('No feature docs yet. plan-feature creates one in the features directory.');
  process.exit(0);
}

let failed = false;
for (const code of codes) {
  const feature = features.get(code);
  const { text } = table(code);
  if (!write) {
    console.log(`# ${code} · ${feature.title} · ${feature.status}\n\n${text}`);
    continue;
  }
  const file = join(ROOT, feature.path);
  const current = readFileSync(file, 'utf8');
  const start = START_RE.exec(current);
  const end = current.indexOf(END);
  if (!start || end < start.index) {
    console.error(`✗ ${feature.path}: no ${END.replace('end', 'start …')} / ${END} markers to write the table between`);
    failed = true;
    continue;
  }
  const next = `${current.slice(0, start.index)}${START}\n\n${text}\n\n${current.slice(end)}`;
  if (next !== current) writeFileSync(file, next);
  console.log(`${next === current ? '=' : '✓'} ${feature.path}`);
}
process.exit(failed ? 1 : 0);
