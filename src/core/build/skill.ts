import { readdir, readFile, realpath, stat } from "node:fs/promises";
import path from "node:path";
import type { Problem } from "../../errors.js";
import { toLF } from "../../util/text.js";

export const GENERATED_COMMENT_PREFIX = "<!-- Generated by metafab build";

const utf8 = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true });

/**
 * Decodes bytes as text only when they are valid UTF-8 and contain no NUL.
 * Everything else is treated as binary and copied unchanged.
 */
export function textContent(data: Uint8Array): string | undefined {
  if (data.indexOf(0) !== -1) return undefined;
  try {
    return utf8.decode(data);
  } catch {
    return undefined;
  }
}

export interface CompiledFile {
  /** Path inside the installed skill directory, with forward slashes. */
  path: string;
  content: Buffer;
  /** Set only for files with an executable bit. */
  mode?: number;
}

export interface SkillSource {
  /** Absolute directory that contains SKILL.md. */
  dir: string;
  /** Installed directory name. Nested groups flatten to this name. */
  name: string;
  /** Repository-relative source directory, used in messages and the generated comment. */
  sourcePath: string;
}

export interface CompileSkillOptions {
  /** Absolute `.factory` directory. Symlinks must resolve inside it. */
  factoryDir: string;
  /** Generated comment line. Defaults to the factory skill comment. */
  comment?: string;
}

export interface CompiledSkill {
  name: string;
  sourcePath: string;
  files: CompiledFile[];
  problems: Problem[];
}

export function generatedComment(sourcePath: string): string {
  return `${GENERATED_COMMENT_PREFIX} from ${sourcePath}/. Edit the source, then run metafab build. -->`;
}

export function builtinComment(version: string): string {
  return `${GENERATED_COMMENT_PREFIX} ${version}. Do not edit. Run metafab build to update. -->`;
}

export async function isOwned(dir: string): Promise<boolean> {
  try {
    const text = await readFile(path.join(dir, "SKILL.md"), "utf8");
    return text.includes(GENERATED_COMMENT_PREFIX);
  } catch {
    return false;
  }
}

function isInside(root: string, target: string): boolean {
  const relative = path.relative(root, target);
  return (
    relative === "" ||
    (!relative.startsWith(`..${path.sep}`) && relative !== ".." && !path.isAbsolute(relative))
  );
}

function insertComment(
  text: string,
  comment: string,
): { ok: true; text: string } | { ok: false; message: string; fix: string } {
  const lines = text.split("\n");
  if (lines[0] !== "---") {
    return {
      ok: false,
      message: "SKILL.md must start with a '---' frontmatter block",
      fix: "Add a frontmatter block that starts with --- and ends with ---",
    };
  }

  const closing = lines.indexOf("---", 1);
  if (closing === -1) {
    return {
      ok: false,
      message: "SKILL.md has unterminated frontmatter",
      fix: "Add a line that contains only --- after the frontmatter",
    };
  }

  lines.splice(closing + 1, 0, comment);
  return { ok: true, text: lines.join("\n") };
}

interface WalkContext {
  factoryDir: string;
  comment: string;
  sourcePath: string;
  files: CompiledFile[];
  problems: Problem[];
}

function addProblem(context: WalkContext, file: string, message: string, fix: string): void {
  context.problems.push({ level: "error", file, line: 1, message, fix });
}

function problemFile(context: WalkContext, relative: string): string {
  return `${context.sourcePath}/${relative}`;
}

async function addFile(
  target: string,
  relative: string,
  context: WalkContext,
  mode?: number,
): Promise<void> {
  let data: Buffer;
  let fileMode: number;
  try {
    data = await readFile(target);
    fileMode = mode ?? (await stat(target)).mode;
  } catch {
    addProblem(
      context,
      problemFile(context, relative),
      `Cannot read file ${problemFile(context, relative)}`,
      "Check its permissions or restore the file",
    );
    return;
  }

  let content = data;
  let text: string | undefined;
  const decoded = textContent(data);
  if (decoded !== undefined) {
    text = toLF(decoded);
    content = Buffer.from(text, "utf8");
  }

  if (relative === "SKILL.md") {
    if (text === undefined) {
      addProblem(
        context,
        problemFile(context, relative),
        "SKILL.md is binary",
        "Replace it with a UTF-8 text file",
      );
      return;
    }
    const inserted = insertComment(text, context.comment);
    if (!inserted.ok) {
      addProblem(context, problemFile(context, relative), inserted.message, inserted.fix);
      return;
    }
    content = Buffer.from(inserted.text, "utf8");
  }

  const file: CompiledFile = { path: relative, content };
  if ((fileMode & 0o111) !== 0) file.mode = fileMode & 0o777;
  context.files.push(file);
}

async function addSymlink(
  target: string,
  relative: string,
  context: WalkContext,
  ancestors: Set<string>,
): Promise<void> {
  let resolved: string;
  try {
    resolved = await realpath(target);
  } catch {
    addProblem(
      context,
      problemFile(context, relative),
      `Symlink ${problemFile(context, relative)} is broken`,
      "Replace it with a regular file inside .factory/",
    );
    return;
  }

  let factoryRoot: string;
  try {
    factoryRoot = await realpath(context.factoryDir);
  } catch {
    addProblem(
      context,
      problemFile(context, relative),
      "Cannot resolve the .factory directory",
      "Restore the .factory directory",
    );
    return;
  }

  if (!isInside(factoryRoot, resolved)) {
    addProblem(
      context,
      problemFile(context, relative),
      `Symlink ${problemFile(context, relative)} points outside .factory/`,
      "Replace it with a regular file inside .factory/, or remove the symlink",
    );
    return;
  }

  let info;
  try {
    info = await stat(resolved);
  } catch {
    addProblem(
      context,
      problemFile(context, relative),
      `Cannot read the target of symlink ${problemFile(context, relative)}`,
      "Replace it with a regular file inside .factory/",
    );
    return;
  }

  if (info.isDirectory()) {
    if (ancestors.has(resolved)) {
      addProblem(
        context,
        problemFile(context, relative),
        `Symlink ${problemFile(context, relative)} creates a loop`,
        "Remove the symlink",
      );
      return;
    }
    await walk(resolved, relative, context, ancestors);
    return;
  }

  if (info.isFile()) {
    await addFile(resolved, relative, context, info.mode);
    return;
  }

  addProblem(
    context,
    problemFile(context, relative),
    `Symlink ${problemFile(context, relative)} does not point to a file or directory`,
    "Replace it with a regular file inside .factory/",
  );
}

async function walk(
  directory: string,
  prefix: string,
  context: WalkContext,
  ancestors: Set<string>,
): Promise<void> {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch {
    const display = prefix === "" ? context.sourcePath : problemFile(context, prefix);
    addProblem(
      context,
      display,
      `Cannot read directory ${display}`,
      "Check its permissions or restore the directory",
    );
    return;
  }

  let ancestry = ancestors;
  try {
    ancestry = new Set([...ancestors, await realpath(directory)]);
  } catch {
    // Keep the ancestors we have; the entries below still report their own problems.
  }

  entries.sort((left, right) => (left.name < right.name ? -1 : left.name > right.name ? 1 : 0));

  for (const entry of entries) {
    const full = path.join(directory, entry.name);
    const relative = prefix === "" ? entry.name : `${prefix}/${entry.name}`;

    if (entry.isSymbolicLink()) {
      await addSymlink(full, relative, context, ancestry);
    } else if (entry.isDirectory()) {
      await walk(full, relative, context, ancestry);
    } else if (entry.isFile()) {
      await addFile(full, relative, context);
    }
  }
}

export async function compileSkill(
  source: SkillSource,
  options: CompileSkillOptions,
): Promise<CompiledSkill> {
  const context: WalkContext = {
    factoryDir: options.factoryDir,
    comment: options.comment ?? generatedComment(source.sourcePath),
    sourcePath: source.sourcePath,
    files: [],
    problems: [],
  };

  await walk(source.dir, "", context, new Set());

  if (!context.files.some((file) => file.path === "SKILL.md") && context.problems.length === 0) {
    addProblem(
      context,
      `${source.sourcePath}/SKILL.md`,
      `Missing SKILL.md in ${source.sourcePath}`,
      "Add a SKILL.md with name and description frontmatter",
    );
  }

  context.files.sort((left, right) =>
    left.path < right.path ? -1 : left.path > right.path ? 1 : 0,
  );

  return {
    name: source.name,
    sourcePath: source.sourcePath,
    files: context.files,
    problems: context.problems,
  };
}
