import { lstat, readFile, realpath, stat } from "node:fs/promises";
import path from "node:path";
import { readdirTyped } from "../../util/fs.js";
import type { Problem } from "../../errors.js";
import { toLF } from "../../util/text.js";
import { markdownParts } from "../env/markdown.js";

export const GENERATED_COMMENT_PREFIX = "<!-- Generated by metafab build";

const utf8 = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true });

/**
 * Decodes bytes as text only when they are valid UTF-8 and contain no NUL.
 * Everything else is treated as binary and copied unchanged.
 */
export function textContent(data: Uint8Array): string | undefined {
  if (data.indexOf(0) !== -1) return undefined;
  try {
    return utf8.decode(data);
  } catch {
    return undefined;
  }
}

export interface CompiledFile {
  /** Path inside the installed skill directory, with forward slashes. */
  path: string;
  content: Buffer;
  /** Installed permission bits: 0o755 when the source has any executable bit, else 0o644. */
  mode: number;
}

export interface SkillSource {
  /** Absolute directory that contains SKILL.md. */
  dir: string;
  /** Installed directory name. Nested groups flatten to this name. */
  name: string;
  /** Repository-relative source directory, used in messages and the generated comment. */
  sourcePath: string;
}

/** One Markdown file handed to a `CompileSkillOptions.render` callback. */
export interface RenderFile {
  /** Path inside the installed skill directory, with forward slashes. */
  relative: string;
  /** LF-normalised body text: everything after the frontmatter, when the file has one. */
  text: string;
  /** Line number of `text`'s first line in the source file. */
  firstLine: number;
}

export interface CompileSkillOptions {
  /** Absolute `.factory` directory. Symlinks must resolve inside it. */
  factoryDir: string;
  /**
   * Extra absolute directories a symlink may resolve into, beside `factoryDir`.
   * Adoption passes the repository's `.factory/`, because a link there is valid
   * after the move; `build` never passes it.
   */
  linkRoots?: string[];
  /** Generated comment line. Defaults to the factory skill comment. */
  comment?: string;
  /**
   * Renders a Markdown file for the environment selection. Absent copies the
   * text unchanged, as the built-in skill and adoption do.
   */
  render?: (file: RenderFile) => string;
  /** A partial match's label, for `**Applies only <label>.**` after the comment. */
  appliesOnly?: string;
}

export interface CompiledSkill {
  name: string;
  sourcePath: string;
  files: CompiledFile[];
  problems: Problem[];
}

/** A source file the walk found, before it is read. */
export interface CollectedFile {
  /** Path inside the installed skill directory, with forward slashes. */
  relative: string;
  /** Absolute path to read, after following a symlink. */
  target: string;
  /** Installed permission bits: 0o755 when the source has any executable bit, else 0o644. */
  mode: number;
}

export interface CollectedSkillFiles {
  /** Sorted by `relative`, so two runs list a tree in the same order. */
  files: CollectedFile[];
  problems: Problem[];
}

export function generatedComment(sourcePath: string): string {
  return `${GENERATED_COMMENT_PREFIX} from ${sourcePath}/. Edit the source, then run metafab build. -->`;
}

export function builtinComment(version: string): string {
  return `${GENERATED_COMMENT_PREFIX} ${version}. Do not edit. Run metafab build to update. -->`;
}

export function cannotReadProblem(relativePath: string): Problem {
  return {
    level: "error",
    file: relativePath,
    line: 1,
    message: `Cannot read ${relativePath}`,
    fix: "Check its permissions",
  };
}

function isReadError(problem: Problem): boolean {
  return problem.message.startsWith("Cannot read ");
}

function isBelow(parent: string, child: string): boolean {
  return child.startsWith(`${parent.replace(/\/+$/, "")}/`);
}

/**
 * Keeps one read error per path. An unreadable directory also makes every path
 * below it unreadable, so its problem explains the rest: keep it and drop the
 * problems it covers. Unreadable paths are collected from the whole list first,
 * so the result does not depend on problem order. Other problems pass through
 * unchanged.
 */
export function dedupeReadErrors(problems: readonly Problem[]): Problem[] {
  const unreadable = new Set(problems.filter(isReadError).map((problem) => problem.file));
  const seen = new Set<string>();

  return problems.filter((problem) => {
    if (!isReadError(problem)) return true;

    if (seen.has(problem.file)) return false;
    seen.add(problem.file);

    for (const file of unreadable) {
      if (isBelow(file, problem.file)) return false;
    }
    return true;
  });
}

function unreadablePath(displayPath: string, error: unknown): Problem | undefined {
  const code = (error as NodeJS.ErrnoException).code;
  if (code === "ENOENT" || code === "ENOTDIR") return undefined;
  return cannotReadProblem(displayPath);
}

/**
 * Reports ownership of an installed skill directory.
 *
 * Returns a Problem when `SKILL.md` exists but cannot be read, so the caller can
 * report one `Cannot read <path>` error instead of treating the entry as unowned.
 * A missing `SKILL.md` (ENOENT/ENOTDIR) is simply not owned.
 */
export async function isOwned(dir: string, displayPath = dir): Promise<boolean | Problem> {
  const skillFile = path.join(dir, "SKILL.md");
  const skillDisplay = `${displayPath}/SKILL.md`;

  let info;
  try {
    info = await lstat(skillFile);
  } catch (error) {
    // lstat does not need permission on the final component, so an error here
    // means the directory itself cannot be traversed.
    return unreadablePath(displayPath, error) ?? false;
  }
  if (!info.isFile()) return false;

  try {
    const text = await readFile(skillFile, "utf8");
    return text.includes(GENERATED_COMMENT_PREFIX);
  } catch (error) {
    return unreadablePath(skillDisplay, error) ?? false;
  }
}

function isInside(root: string, target: string): boolean {
  const relative = path.relative(root, target);
  return (
    relative === "" ||
    (!relative.startsWith(`..${path.sep}`) && relative !== ".." && !path.isAbsolute(relative))
  );
}

/** True for a file `build` renders: its extension, lowercased, is `.md`. */
function isMarkdown(relative: string): boolean {
  return path.extname(relative).toLowerCase() === ".md";
}

/** A Markdown file's text for the selection; anything else is left alone. */
function renderMarkdown(
  relative: string,
  text: string,
  firstLine: number,
  options: CompileSkillOptions,
): string {
  if (options.render === undefined || !isMarkdown(relative)) return text;
  return options.render({ relative, text, firstLine });
}

/**
 * Inserts the generated comment after the frontmatter, and the `Applies only`
 * line after it when the skill applies in some environments only. Only the body
 * below the frontmatter is rendered, so name and description stay the same in
 * every environment.
 */
function insertComment(
  text: string,
  comment: string,
  options: CompileSkillOptions,
): { ok: true; text: string } | { ok: false; message: string; fix: string } {
  const parts = markdownParts(text);
  if (parts.frontmatter === undefined) {
    return {
      ok: false,
      message: "SKILL.md must start with a '---' frontmatter block",
      fix: "Add a frontmatter block that starts with --- and ends with ---",
    };
  }
  if (!parts.closed) {
    return {
      ok: false,
      message: "SKILL.md has unterminated frontmatter",
      fix: "Add a line that contains only --- after the frontmatter",
    };
  }

  const rendered = renderMarkdown("SKILL.md", parts.body, parts.firstLine, options).split("\n");
  // `prefix` ends with the newline that starts the body, or with the closing
  // `---` itself when the file ends there, so only then does the comment need
  // one of its own.
  const head = `${parts.prefix}${parts.prefix.endsWith("\n") ? "" : "\n"}${comment}`;
  const next = [head];
  if (options.appliesOnly !== undefined) next.push(`**Applies only ${options.appliesOnly}.**`);
  // A file that ends at its closing `---` has no body line, not even the empty
  // one a final newline leaves behind.
  if (parts.body !== "" || text.endsWith("\n")) next.push(...rendered);
  return { ok: true, text: next.join("\n") };
}

interface WalkContext {
  factoryDir: string;
  linkRoots: readonly string[];
  sourcePath: string;
  files: CollectedFile[];
  problems: Problem[];
}

function addProblem(context: WalkContext, file: string, message: string, fix: string): void {
  context.problems.push({ level: "error", file, line: 1, message, fix });
}

function problemFile(context: WalkContext, relative: string): string {
  return `${context.sourcePath}/${relative}`;
}

async function addFile(
  target: string,
  relative: string,
  context: WalkContext,
  mode?: number,
): Promise<void> {
  let fileMode: number;
  try {
    fileMode = mode ?? (await stat(target)).mode;
  } catch {
    addProblem(
      context,
      problemFile(context, relative),
      `Cannot read file ${problemFile(context, relative)}`,
      "Check its permissions or restore the file",
    );
    return;
  }

  context.files.push({
    relative,
    target,
    mode: (fileMode & 0o111) !== 0 ? 0o755 : 0o644,
  });
}

async function addSymlink(
  target: string,
  relative: string,
  context: WalkContext,
  ancestors: Set<string>,
): Promise<void> {
  let resolved: string;
  try {
    resolved = await realpath(target);
  } catch {
    addProblem(
      context,
      problemFile(context, relative),
      `Symlink ${problemFile(context, relative)} is broken`,
      "Replace it with a regular file inside .factory/",
    );
    return;
  }

  let factoryRoot: string;
  try {
    factoryRoot = await realpath(context.factoryDir);
  } catch {
    addProblem(
      context,
      problemFile(context, relative),
      "Cannot resolve the .factory directory",
      "Restore the .factory directory",
    );
    return;
  }

  // A listed root that cannot be resolved accepts nothing; it never turns into
  // a read error of its own.
  const roots = [factoryRoot];
  for (const linkRoot of context.linkRoots) {
    try {
      roots.push(await realpath(linkRoot));
    } catch {
      // Ignore it.
    }
  }

  if (!roots.some((root) => isInside(root, resolved))) {
    addProblem(
      context,
      problemFile(context, relative),
      `Symlink ${problemFile(context, relative)} points outside .factory/`,
      "Replace it with a regular file inside .factory/, or remove the symlink",
    );
    return;
  }

  let info;
  try {
    info = await stat(resolved);
  } catch {
    addProblem(
      context,
      problemFile(context, relative),
      `Cannot read the target of symlink ${problemFile(context, relative)}`,
      "Replace it with a regular file inside .factory/",
    );
    return;
  }

  if (info.isDirectory()) {
    if (ancestors.has(resolved)) {
      addProblem(
        context,
        problemFile(context, relative),
        `Symlink ${problemFile(context, relative)} creates a loop`,
        "Remove the symlink",
      );
      return;
    }
    await walk(resolved, relative, context, ancestors);
    return;
  }

  if (info.isFile()) {
    await addFile(resolved, relative, context, info.mode);
    return;
  }

  addProblem(
    context,
    problemFile(context, relative),
    `Symlink ${problemFile(context, relative)} does not point to a file or directory`,
    "Replace it with a regular file inside .factory/",
  );
}

async function walk(
  directory: string,
  prefix: string,
  context: WalkContext,
  ancestors: Set<string>,
): Promise<void> {
  let entries;
  try {
    entries = await readdirTyped(directory);
  } catch {
    const display = prefix === "" ? context.sourcePath : problemFile(context, prefix);
    addProblem(
      context,
      display,
      `Cannot read directory ${display}`,
      "Check its permissions or restore the directory",
    );
    return;
  }

  let ancestry = ancestors;
  try {
    ancestry = new Set([...ancestors, await realpath(directory)]);
  } catch {
    // Keep the ancestors we have; the entries below still report their own problems.
  }

  entries.sort((left, right) => (left.name < right.name ? -1 : left.name > right.name ? 1 : 0));

  for (const entry of entries) {
    const full = path.join(directory, entry.name);
    const relative = prefix === "" ? entry.name : `${prefix}/${entry.name}`;

    if (entry.isSymbolicLink()) {
      await addSymlink(full, relative, context, ancestry);
    } else if (entry.isDirectory()) {
      await walk(full, relative, context, ancestry);
    } else if (entry.isFile()) {
      await addFile(full, relative, context);
    }
  }
}

/**
 * Lists a skill's source files as `build` installs them, with the symlink
 * containment and loop rules of the walk. `compileSkill` reads the files it
 * returns; the environment validation walks the same list to check every
 * Markdown file `build` would render.
 */
export async function collectSkillFiles(
  source: SkillSource,
  options: CompileSkillOptions,
): Promise<CollectedSkillFiles> {
  const context: WalkContext = {
    factoryDir: options.factoryDir,
    linkRoots: options.linkRoots ?? [],
    sourcePath: source.sourcePath,
    files: [],
    problems: [],
  };

  await walk(source.dir, "", context, new Set());

  context.files.sort((left, right) =>
    left.relative < right.relative ? -1 : left.relative > right.relative ? 1 : 0,
  );

  return { files: context.files, problems: context.problems };
}

/**
 * Reads one collected file into its installed content: text is written as LF,
 * Markdown is rendered for the selection, and `SKILL.md` gains the generated
 * comment after its frontmatter. A file that cannot be read, or a `SKILL.md`
 * that is binary or has no frontmatter, reports its problem and is left out.
 */
async function compiledFile(
  file: CollectedFile,
  displayPath: string,
  comment: string,
  options: CompileSkillOptions,
  problems: Problem[],
): Promise<CompiledFile | undefined> {
  const error = (message: string, fix: string): undefined => {
    problems.push({ level: "error", file: displayPath, line: 1, message, fix });
    return undefined;
  };

  let data: Buffer;
  try {
    data = await readFile(file.target);
  } catch {
    return error(`Cannot read file ${displayPath}`, "Check its permissions or restore the file");
  }

  const decoded = textContent(data);
  if (decoded === undefined) {
    if (file.relative === "SKILL.md") {
      return error("SKILL.md is binary", "Replace it with a UTF-8 text file");
    }
    return { path: file.relative, content: data, mode: file.mode };
  }

  const text = toLF(decoded);
  if (file.relative !== "SKILL.md") {
    // Only a Markdown file with a renderer is split and rendered. Every other
    // file is written as read, byte for byte, so format 1 output and the
    // built-in skill never change.
    if (options.render === undefined || !isMarkdown(file.relative)) {
      return { path: file.relative, content: Buffer.from(text, "utf8"), mode: file.mode };
    }
    // The frontmatter is kept byte for byte and only the body is rendered, the
    // same split validation parses, so a fence in frontmatter cannot hide a
    // directive in the body.
    const parts = markdownParts(text);
    const rendered = renderMarkdown(file.relative, parts.body, parts.firstLine, options);
    return {
      path: file.relative,
      content: Buffer.from(`${parts.prefix}${rendered}`, "utf8"),
      mode: file.mode,
    };
  }

  const inserted = insertComment(text, comment, options);
  if (!inserted.ok) return error(inserted.message, inserted.fix);

  return { path: file.relative, content: Buffer.from(inserted.text, "utf8"), mode: file.mode };
}

export async function compileSkill(
  source: SkillSource,
  options: CompileSkillOptions,
): Promise<CompiledSkill> {
  const collected = await collectSkillFiles(source, options);
  const problems = [...collected.problems];
  const files: CompiledFile[] = [];
  const comment = options.comment ?? generatedComment(source.sourcePath);

  for (const file of collected.files) {
    const compiled = await compiledFile(
      file,
      `${source.sourcePath}/${file.relative}`,
      comment,
      options,
      problems,
    );
    if (compiled !== undefined) files.push(compiled);
  }

  if (!files.some((file) => file.path === "SKILL.md") && problems.length === 0) {
    problems.push({
      level: "error",
      file: `${source.sourcePath}/SKILL.md`,
      line: 1,
      message: `Missing SKILL.md in ${source.sourcePath}`,
      fix: "Add a SKILL.md with name and description frontmatter",
    });
  }

  return {
    name: source.name,
    sourcePath: source.sourcePath,
    files,
    problems,
  };
}
