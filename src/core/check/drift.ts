import { lstat, readFile } from "node:fs/promises";
import path from "node:path";
import type { Problem } from "../../errors.js";
import { fileMatches } from "../build/plan.js";
import type { BuildPlan, BuildWrite, FileMatch } from "../build/plan.js";
import { cannotReadProblem } from "../build/skill.js";
import { destinations } from "../config/destinations.js";
import type { Config } from "../config/types.js";
import type { Factory } from "../factory/types.js";

const ROOT_BLOCK_FILES = new Set(["AGENTS.md", "CLAUDE.md", ".gitignore"]);

/** Every skill destination the configuration can select. */
const SKILL_DIRECTORIES = destinations(["claude", "codex"]).map(
  (destination) => destination.directory,
);

const BUILTIN_VERSION = /Generated by metafab build (\S+?)\. Do not edit\./;

function absolute(root: string, relativePath: string): string {
  return path.join(root, ...relativePath.split("/"));
}

function underAny(target: string, prefixes: readonly string[]): boolean {
  return prefixes.some(
    (prefix) => target === prefix || target.startsWith(`${prefix}/`),
  );
}

function formatMode(mode: number): string {
  return `0${(mode & 0o777).toString(8).padStart(3, "0")}`;
}

function driftProblem(file: string, message: string, fix: string): Problem {
  return { level: "error", file, line: 1, message, fix };
}

function missingSkillsProblem(directory: string, names: readonly string[]): Problem {
  const quoted = names.map((name) => `'${name}'`).join(", ");
  if (names.length === 1) {
    const name = names[0]!;
    return driftProblem(
      `${directory}/${name}`,
      `Installed skill '${name}' is missing from ${directory}`,
      "Run metafab build",
    );
  }

  return driftProblem(
    `${directory}`,
    `Installed skills ${quoted} are missing from ${directory}`,
    "Run metafab build",
  );
}

function differsProblem(
  writePath: string,
  skillName: string,
  sourceBySkill: ReadonlyMap<string, string>,
): Problem {
  const relDir = sourceBySkill.get(skillName);
  const fix =
    relDir === undefined
      ? "Run metafab build"
      : `Edit .factory/${relDir}/ instead, then run metafab build`;
  return driftProblem(writePath, `${writePath} differs from the build output`, fix);
}

function modeProblem(write: BuildWrite, match: FileMatch): Problem {
  const expected = write.mode ?? 0;
  const installed = match.mode ?? 0;
  return driftProblem(
    write.path,
    `${write.path} has mode ${formatMode(installed)}; expected ${formatMode(expected)}`,
    "Run metafab build",
  );
}

function builtinVersionProblem(
  directory: string,
  installedVersion: string,
  cliVersion: string,
): Problem {
  return driftProblem(
    `${directory}/metafab`,
    `The installed metafab skill is from ${installedVersion}; this CLI is ${cliVersion}`,
    "Run metafab build",
  );
}

function blockProblem(file: string): Problem {
  return driftProblem(file, `${file} factory block is out of date`, "Run metafab build");
}

function noSourceProblem(file: string): Problem {
  return driftProblem(file, `${file} has no source in .factory/`, "Run metafab build");
}

function deselectedDestinationProblem(file: string): Problem {
  return driftProblem(
    file,
    `${file} is installed for an agent tool that is no longer configured`,
    "Run metafab build",
  );
}

function inDeselectedDestination(file: string, selected: ReadonlySet<string>): boolean {
  return SKILL_DIRECTORIES.some(
    (directory) => !selected.has(directory) && underAny(file, [directory]),
  );
}

type DirectoryState = "directory" | "missing" | "other" | "unknown";

async function directoryState(target: string): Promise<DirectoryState> {
  try {
    const info = await lstat(target);
    return info.isDirectory() ? "directory" : "other";
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code;
    if (code === "ENOENT" || code === "ENOTDIR") return "missing";
    return "unknown";
  }
}

async function readInstalledVersion(
  root: string,
  skillDirectory: string,
): Promise<string | undefined> {
  try {
    const text = await readFile(absolute(root, `${skillDirectory}/SKILL.md`), "utf8");
    return BUILTIN_VERSION.exec(text)?.[1];
  } catch {
    return undefined;
  }
}

async function safeFileMatches(root: string, write: BuildWrite): Promise<FileMatch | Problem> {
  try {
    return await fileMatches(root, write);
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code;
    if (code === "EACCES" || code === "EPERM") return cannotReadProblem(write.path);
    throw error;
  }
}

interface SkillWrites {
  name: string;
  writes: BuildWrite[];
}

function skillWritesByDestination(
  writes: readonly BuildWrite[],
  directory: string,
): SkillWrites[] {
  const prefix = `${directory}/`;
  const byName = new Map<string, SkillWrites>();

  for (const write of writes) {
    if (!write.path.startsWith(prefix)) continue;
    const rest = write.path.slice(prefix.length);
    const slash = rest.indexOf("/");
    if (slash === -1) continue;
    const name = rest.slice(0, slash);
    const existing = byName.get(name);
    if (existing === undefined) {
      byName.set(name, { name, writes: [write] });
    } else {
      existing.writes.push(write);
    }
  }

  return [...byName.values()];
}

function deepestRemovals(removals: readonly string[]): string[] {
  const unique = [...new Set(removals)].sort();
  return unique.filter(
    (candidate) =>
      !unique.some((other) => other !== candidate && other.startsWith(`${candidate}/`)),
  );
}

/**
 * Compares the installed output with the writes `planBuild` would make.
 *
 * Every difference is one problem. Missing installed skills collapse into one
 * problem per destination so a fresh clone gives a short report.
 */
export async function compareBuildOutput(
  factory: Factory,
  config: Config,
  plan: BuildPlan,
  cliVersion: string,
): Promise<Problem[]> {
  const problems: Problem[] = [];
  const root = plan.root;
  const conflictPaths = plan.conflicts.map((problem) => problem.file);
  const sourceBySkill = new Map(factory.skills.map((skill) => [skill.name, skill.relDir]));
  const selected = destinations(config.agents);
  const selectedDirectories = new Set(selected.map((destination) => destination.directory));

  for (const destination of selected) {
    const directory = destination.directory;
    const skills = skillWritesByDestination(plan.writes, directory);
    const missing: string[] = [];

    for (const skill of skills) {
      const skillDirectory = `${directory}/${skill.name}`;
      if (underAny(skillDirectory, conflictPaths)) continue;

      const state = await directoryState(absolute(root, skillDirectory));
      if (state === "missing") {
        missing.push(skill.name);
        continue;
      }
      if (state !== "directory") continue;

      if (skill.name === "metafab" && config.metafabSkill) {
        const installedVersion = await readInstalledVersion(root, skillDirectory);
        if (installedVersion !== undefined && installedVersion !== cliVersion) {
          problems.push(builtinVersionProblem(directory, installedVersion, cliVersion));
          continue;
        }
      }

      for (const write of skill.writes) {
        const match = await safeFileMatches(root, write);
        if ("level" in match) {
          problems.push(match);
          continue;
        }
        if (!match.exists || !match.contentSame) {
          problems.push(differsProblem(write.path, skill.name, sourceBySkill));
        } else if (!match.modeSame) {
          problems.push(modeProblem(write, match));
        }
      }
    }

    if (missing.length > 0) problems.push(missingSkillsProblem(directory, missing));
  }

  for (const write of plan.writes) {
    if (!ROOT_BLOCK_FILES.has(write.path)) continue;
    if (underAny(write.path, conflictPaths)) continue;

    const match = await safeFileMatches(root, write);
    if ("level" in match) {
      problems.push(match);
      continue;
    }
    if (!match.same) problems.push(blockProblem(write.path));
  }

  for (const removal of deepestRemovals(plan.removals)) {
    if (underAny(removal, conflictPaths)) continue;
    if (ROOT_BLOCK_FILES.has(removal)) {
      problems.push(blockProblem(removal));
    } else if (inDeselectedDestination(removal, selectedDirectories)) {
      problems.push(deselectedDestinationProblem(removal));
    } else {
      problems.push(noSourceProblem(removal));
    }
  }

  for (const conflict of plan.conflicts) {
    const unowned =
      conflict.message.startsWith("Unowned directory ") ||
      conflict.message.startsWith("Unowned file ");
    problems.push({
      ...conflict,
      // A problem about a path has no line of its own; the report always shows one.
      line: conflict.line ?? 1,
      ...(unowned ? { fix: "Move it into .factory/skills/ or rename it" } : {}),
    });
  }

  return problems;
}
